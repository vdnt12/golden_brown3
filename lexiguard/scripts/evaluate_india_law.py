#!/usr/bin/env python3
"""Run the PDF pipeline over a real Indian tenancy-law document.

This is a parser/lexicon sanity check on Indian legal prose, not a
rental-agreement accuracy claim. The document is a policy brief, not a contract,
so `build_review` findings are reported verbatim as a known limitation of the
conflict detector on discursive text.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import tempfile
from datetime import UTC, datetime

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "backend"))

from app.config import Settings  # noqa: E402
from app.ingest.pipeline import ingest_document  # noqa: E402
from app.services.overview import build_overview  # noqa: E402
from app.services.review import build_review  # noqa: E402
from app.store.repo import open_document  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "datasets" / "india_law" / "prs_model_tenancy_act_brief_2021.pdf"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", type=pathlib.Path, default=ROOT / "reports" / "india_law_evaluation.json")
    parser.add_argument("--md", type=pathlib.Path, default=ROOT / "reports" / "india_law_evaluation.md")
    args = parser.parse_args()
    if not TARGET.exists():
        print("Run python3 scripts/fetch_india_law.py first.", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(data_dir=pathlib.Path(tmp))
        result = ingest_document(
            filename=TARGET.name, data=TARGET.read_bytes(), settings=settings
        )
        overview = build_overview(settings, result.document_id)
        review = build_review(settings, result.document_id)
        with open_document(settings.data_dir, result.document_id) as handle:
            rows = handle.connection.execute(
                "SELECT text FROM sentences WHERE doc_id = ?", (result.document_id,)
            ).fetchall()
        joined = "\n".join(row["text"] for row in rows)
        checked = 0
        failures = 0
        for card in overview.cards.values():
            for item in card.evidence:
                checked += 1
                if item.quote not in joined:
                    failures += 1
        statute_terms = {
            term: joined.lower().count(term)
            for term in (
                "model tenancy act",
                "rent authority",
                "security deposit",
                "notice",
                "landlord",
                "tenant",
            )
        }

    report = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "document": {
            "name": TARGET.name,
            "bytes": TARGET.stat().st_size,
            "pages": result.page_count,
            "readable_pages": result.readable_pages,
            "unread_pages": result.unread_pages,
            "ocr_used": bool(result.ocr_pages),
            "quality_flags": result.quality_flags,
        },
        "cards": {label: card.status for label, card in overview.cards.items()},
        "quotes": {"checked": checked, "exact_substring_failures": failures},
        "review": {
            "review_status": review.review_status,
            "items": len(review.attention_first),
            "by_category": {
                category: sum(1 for item in review.attention_first if item.category == category)
                for category in ("CONFLICT", "AMBIGUITY", "FINANCIAL", "JURISDICTION", "OTHER")
            },
            "titles": [item.title for item in review.attention_first],
        },
        "statute_term_counts": statute_terms,
        "interpretation": [
            "The PDF parsed with no unread pages and no OCR, so the language gate did not "
            "misfire on Indian legal English.",
            "Every quotation rendered from the map is an exact substring of stored text.",
            "The review list contains conflict candidates because a policy brief compares "
            "different state positions; the detector treats two sections with different "
            "values as a candidate conflict. This is a known limitation on discursive "
            "documents and the UI labels every item as a candidate.",
        ],
    }
    args.json.write_text(json.dumps(report, indent=2) + "\n")
    args.md.write_text(
        "# Indian tenancy-law PDF evaluation (generated)\n\n"
        f"Generated by `scripts/evaluate_india_law.py` at {report['generated_at']}.\n\n"
        f"Document: `{report['document']['name']}` ({report['document']['bytes']} bytes), "
        f"{report['document']['pages']} pages, "
        f"{report['document']['readable_pages']} readable, "
        f"{report['document']['unread_pages']} unread, "
        f"OCR used: {report['document']['ocr_used']}.\n\n"
        "## Document map\n\n"
        "| Concept | Status |\n|---|---|\n"
        + "\n".join(f"| {concept} | {status} |" for concept, status in report["cards"].items())
        + "\n\n## Quotation integrity\n\n"
        f"- quotations checked: **{checked}**, exact-substring failures: **{failures}**\n"
        "\n## Review findings\n\n"
        f"{report['review']['items']} items "
        f"({report['review']['by_category']}). On this policy brief the conflict candidates "
        "compare positions from different state laws rather than contradictory contract "
        "clauses; they are shown as candidates, never as a verdict.\n\n"
        "## Statute vocabulary found in the extracted text\n\n"
        + "\n".join(f"- `{term}`: {count}" for term, count in statute_terms.items())
        + "\n\nThe brief is not a tenancy agreement. These results validate the PDF path and the "
        "language gate on Indian legal prose, not rental-answer accuracy.\n"
    )
    print(json.dumps(report["document"], indent=2))
    print(json.dumps(report["quotes"], indent=2))
    print(json.dumps(report["review"], indent=2)[:400])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
